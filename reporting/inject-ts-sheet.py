def med(xs):
    xs = [x for x in xs if x is not None]
    return round(statistics.median(xs), 1) if xs else None

def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p)) if os.path.exists(p) else []

def aggregate():
    data = (load("results-ts.json") + load("results-cloud-ts.json") + load("results-fable5-ts.json")
            + load("results-morph-ts.json") + load("results-fast100-ts.json"))
    by = {}
    for r in data:
        by.setdefault(r["model"], []).append(r)
    rows = []
    for model, recs in by.items():
        single  = [r for r in recs if r.get("mode") == "single"  and r.get("ok")]
        # `err` marks a run the client refused rather than a real failure (e.g. the Claude Code
        # client rejects agentic tool-loops) — exclude it so A%/toolValid read N/A, not a false 0.
        agentic = [r for r in recs if r.get("mode") == "agentic" and r.get("ok") and not r.get("err")]
        if not single and not agentic:
            continue  # load-failure only -> nothing to report
        name, group, price, ctx = META.get(model, (model, "local", "local", "—"))
        scost = [r.get("cost", 0) for r in single]
        reasoning = "yes" if any((r.get("reasonTok") or 0) > 0 for r in single + agentic) else "no"
        rows.append(dict(
            model=model, name=name, group=group, price=price, ctx=ctx, reasoning=reasoning,
            S=round(100 * sum(r["pct"] for r in single) / len(single)) if single else None,
            full=f"{sum(1 for r in single if r['pct'] >= 0.999)}/{len(single)}" if single else "—",
            typp=round(100 * sum(1 for r in single if r.get("typechecks")) / len(single)) if single else None,
            cost=round(sum(scost) / len(scost), 5) if any(scost) else 0,
            medLat=med([r["latency"] for r in single]),
            medRsn=round(med([r["reasonTok"] for r in single]) or 0),
            A=round(100 * sum(r["pct"] for r in agentic) / len(agentic)) if agentic else None,
            green=f"{sum(1 for r in agentic if r.get('visibleGreen'))}/{len(agentic)}" if agentic else "—",
            toolValid=round(100 * sum(r.get("toolValidPct", 0) for r in agentic) / len(agentic)) if agentic else None,
            recovered=f"{sum(1 for r in agentic if r.get('recovered'))}/{len(agentic)}" if agentic else "—",
            tokps=med([r["tokps"] for r in single if r.get("tokps")]),
            ttft=med([r["ttft"] for r in single if r.get("ttft") is not None]),
        ))
    # group "sub" (Claude Code subscription): blank the harness-inflated / non-comparable columns.
    # Speed (tok/s, TTFT, latency) is dominated by ~46k-token harness prefill; $/task is an
    # API-equivalent, not a real per-token charge; reasoning tokens aren't exposed by `claude -p`.
    # Correctness columns (S%, type%) stay — the objective tsc+bun oracle is robust to this.
    for r in rows:
        if r["group"] == "sub":
            r["cost"] = 0; r["medLat"] = None; r["medRsn"] = None; r["tokps"] = None; r["ttft"] = None

    # local models first, ranked by agentic then single; cloud refs pinned to the bottom.
    locals_ = [r for r in rows if r["group"] == "local"]
    refs = [r for r in rows if r["group"] != "local"]
    locals_.sort(key=lambda r: (-(r["A"] or 0), -(r["S"] or 0)))
    refs.sort(key=lambda r: (-(r["A"] or 0), -(r["S"] or 0)))
    return locals_ + refs

