#   * register the relationship in xl/_rels/workbook.xml.rels
#   * register the content-type Override in [Content_Types].xml
# Everything else in the archive is copied verbatim. A timestamped backup is made first.
#
# Aggregates are computed from results-ts.json (local) + results-cloud-ts.json (cloud refs).
# Usage: python3 inject-ts-sheet.py [path-to-xlsx]

