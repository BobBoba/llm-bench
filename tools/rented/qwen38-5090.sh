#!/usr/bin/env bash
# llama-server для Qwen3.8-27B на арендованной RTX 5090 (32.6 ГиБ, Clore, контейнер Ubuntu).
#
# Параметры подобраны замерами 20.08.2026 на этой самой карте, а не перенесены с 3090:
#   * KV-кэш q4_0, несмотря на запас памяти. Точный q8_0 проверялся честно и НЕ ДАЁТ НИЧЕГО:
#     hard-bench 42/66 против 47/66 у грубого (разница 0.93 стандартной ошибки, то есть шум),
#     а поиск иглами 8/8 на ВСЕХ ступенях вплоть до 245713 токенов у обоих. Значит 4.1 ГиБ
#     тратить не на что. Смешивать точности НЕЛЬЗЯ: K=q8_0/V=q4_0 роняет скорость до 133.7 т/с
#     (разнотипный кэш уводит на медленный путь ядра).
#   * Квант Q3_K_XL. Старшие проверены на РАВНОМ полном окне по 66 измерений каждый:
#     Q3 0.712 решённых, Q4 0.697, Q5 0.727 — все различия в пределах шума, зато скорость
#     падает со 155 до 141 и 125 т/с. Платить скоростью не за что.
#   * Слотов 4, а не 2: на этой карте памяти хватает, одиночный запрос не замедляется
#     (159.5 против 159.7 т/с), а суммарная пропускная способность растёт до 341 т/с.
#   * Размер батча НЕ трогать. -b 8192 -ub 4096 не ускоряет предобработку вовсе
#     (3246 против 3291 т/с), но съедает лишние 4.6 ГиБ видеопамяти.
#   * Потолок карты: 29.0 ГиБ работает, 30.2 ГиБ — уже утечка KV в оперативную память
#     (признак: RSS выше ~2.8 ГиБ при простое GPU; на утёкшей точке RSS 5163 МиБ, GPU 42%).
#   * Полное родное окно 262144; поднимать пул сверх него бессмысленно — кэш промптов
#     живёт в ОЗУ (--cache-ram, умолчание 8 ГиБ), проверено на 3090 19.08.2026.
#
# ! Порт слушается на 127.0.0.1, а НЕ на 0.0.0.0: у Clore порт контейнера публичный, и
#   сервер с --host 0.0.0.0 отдаёт модель любому, кто просканирует адрес. Доступ снаружи —
#   через SSH-туннель. Ключ API обязателен и лежит в /root/.apikey (0600).
# ! СЭМПЛИНГ ЗАДАЁМ НА СЕРВЕРЕ, а не только в клиенте. Рекомендация Unsloth для Qwen3.8-27B
#   в режиме размышления: temperature=1.0, top_p=0.95, top_k=20, min_p=0.0, presence_penalty=0.0,
#   repeat_penalty=1.0. Совпадают с умолчаниями llama.cpp только два последних, а `min_p` по
#   умолчанию 0.05 — то есть без явного указания модель работает НЕ на рекомендованных настройках,
#   и заметить это по журналу нельзя. Клиент может прислать свои значения и переопределить эти.
set -u
QUANT="${QUANT:-Q3_K_XL}"
KV="${KV:-q4_0}"
# ЧИСЛО СЛОТОВ. ОДИН — для агентной работы с длинным контекстом это оптимум, а не компромисс.
# Замер (4 сессии по 80781 токену, одна и та же работа, стенное время до последнего ответа):
#   1 слот  -> 149.3 с   (очередь; 323124 токена = 2164 т/с, близко к одиночному пределу карты)
#   2 слота -> 276.9 с
#   4 слота -> 355.9 с   (с -b 8192 -ub 2048: 305.9 с; с -b 16384 -ub 4096: 292.3 с)
#   8 слотов на перегруженном пуле -> генерация падает до 0.94 т/с на сессию
# То есть слоты для ДЛИННЫХ контекстов не складываются, а конкурируют: предобработка и так
# насыщает карту, а расщепление добавляет накладные расходы без выигрыша в параллелизме.
# Даже последний в очереди запрос при одном слоте заканчивается раньше (149 с против 356 с).
# ! Обратное верно для КОРОТКИХ запросов: там 2 слота дают +48%, а 4 на 5090 — до 341 т/с
#   суммарно. Прежняя рекомендация «слотов побольше» была получена промптами по 27 токенов,
#   то есть мерила только декодирование, и для агентной нагрузки оказалась вредной.
# Переключение между сессиями при одном слоте не страдает: кэш промптов живёт в ОЗУ
# (`--cache-ram`), простаивающий слот сохраняется туда и восстанавливается при возврате.
PARALLEL="${PARALLEL:-1}"
EFFORT="${EFFORT:-medium}"
CTX="${CTX:-262144}"

# КЭШ ПРОМПТОВ В ОПЕРАТИВНОЙ ПАМЯТИ. Единственный резерв, который на этой карте ещё не занят:
# видеопамятью выжато всё (полное окно 262144, пул сверх него слоту недоступен), а `--cache-ram`
# по умолчанию всего 8192 МиБ. Сюда `--cache-idle-slots` складывает простаивающие слоты, и
# именно отсюда сессия возвращается без повторной предобработки. Одна полноразмерная сессия на
# 262k занимает ~7.4 ГиБ, значит 32 ГиБ держат в горячем виде четыре сессии вместо одной.
# Стоит только оперативной памяти (на машине 62 ГиБ, свободно ~43), видеопамять не трогает.
CRAM="${CRAM:-32768}"
HOSTBIND="${HOSTBIND:-127.0.0.1}"
M="/models/Qwen3.8-27B-UD-$QUANT.gguf"
[ -f "$M" ] || { echo "нет файла $M"; exit 1; }
[ -f /root/.apikey ] || { echo "нет /root/.apikey"; exit 1; }
echo "модель: $M | KV: $KV | слотов: $PARALLEL | усилие: $EFFORT | окно: $CTX"
exec /opt/bin/llama-server \
  -m "$M" \
  --host "$HOSTBIND" --port 8099 \
  --api-key "$(cat /root/.apikey)" \
  -c "$CTX" --cache-ram "$CRAM" \
  --cache-type-k "$KV" --cache-type-v "$KV" \
  --flash-attn on --jinja -ngl -1 --kv-unified --parallel "$PARALLEL" \
  --spec-type draft-mtp --spec-draft-n-max 2 \
  --min-p 0 --top-k 20 --top-p 0.95 --temp 1.0 \
  --chat-template-kwargs "{\"reasoning_effort\":\"$EFFORT\"}"
