#!/usr/bin/env bash
# Голый llama-server для Qwen3.8-27B на ПОЛНОМ родном окне 262144 — обход потолка прослойки.
#
# ЗАЧЕМ. Через Unsloth Studio длинный контекст ломается около ~190k: ответ приходит ПУСТОЙ при
# HTTP 200 (`finish: stop`), `usage.prompt_tokens` показывает ~68k вместо фактических ~194k,
# а иногда служба просто падает («peer closed connection»). Замерено на четырёх квантах —
# картина одинаковая, то есть дело не в модели. Тот же промпт на голом сервере: recall 8/8
# на 196k И на 229k, честный `promptTok` (193323 / 225501) и втрое быстрее.
#
# YaRN/--override-kv здесь НЕ нужны: у Qwen3.8 родное окно и есть 262144.
#
# Использование: QUANT=UD-Q2_K_XL KV_POOL=262144 qwen38-longctx-server.sh
#   QUANT   — UD-Q3_K_XL (умолчание) | UD-Q2_K_XL | UD-IQ2_M | UD-IQ2_XXS | UD-Q4_K_XL
#   KV_POOL — ёмкость KV-пула; менять почти никогда не нужно, см. ниже.
# Перед запуском: выгрузить модель из Studio (запрос к unsloth/Qwen3-0.6B-GGUF) и `gui-off -y`.
# ! СЭМПЛИНГ ЗАДАЁМ НА СЕРВЕРЕ, а не только в клиенте. Рекомендация Unsloth для Qwen3.8-27B
#   в режиме размышления: temperature=1.0, top_p=0.95, top_k=20, min_p=0.0, presence_penalty=0.0,
#   repeat_penalty=1.0. Совпадают с умолчаниями llama.cpp только два последних, а `min_p` по
#   умолчанию 0.05 — то есть без явного указания модель работает НЕ на рекомендованных настройках,
#   и заметить это по журналу нельзя. Клиент может прислать свои значения и переопределить эти.
set -u

# ВЫБОР КВАНТА. Замер всех пяти на ОДНОМ окне 262144 (24 ГиБ, графика выключена):
#   квант        вес     VRAM      скорость   качество (контроль на общем окне 65536)
#   IQ2_XXS      8.4 ГБ  16.3 ГиБ  72.6 т/с   11/18, средний балл 0.731
#   IQ2_M        9.7 ГБ  17.6 ГиБ  77.5 т/с   11/18, средний балл 0.647
#   Q2_K_XL       10 ГБ  17.9 ГиБ  76.8 т/с   12/18, средний балл 0.786
#   Q3_K_XL       13 ГБ  20.4 ГиБ  77.4 т/с   13/18, средний балл 0.800  <- лучший по обеим осям
#   Q4_K_XL       17 ГБ  22.3 ГиБ  28.5 т/с   10/18 — на полном окне УТЕКАЕТ В ОЗУ, см. ниже
# Q3_K_XL выигрывает и по качеству, и по скорости, и держит полное окно — брать его.
# Младшие кванты тут бессмысленны: I-кванты (IQ2_*) распаковываются дороже K-квантов, поэтому
# IQ2_XXS при вдвое меньшем весе даже МЕДЛЕННЕЕ, чем Q3_K_XL. Экономить видеопамять не на что.
# Q4_K_XL на полном окне брать нельзя: 22.3 ГиБ — уже за обрывом (ниже), скорость падает втрое.
QUANT="${QUANT:-UD-Q3_K_XL}"

# ЁМКОСТЬ ПУЛА. Ровно родное окно, и поднимать его НЕ НУЖНО — вопреки первоначальной догадке.
# Два измерения, которые это решают:
#  1. Пул сверх окна не даёт лишних кэшированных сессий. Кэш промптов живёт не в видеопамяти,
#     а в оперативной: `--cache-ram` (умолчание 8192 МиБ) плюс `--cache-idle-slots` сохраняют
#     туда простаивающие слоты. Проверено: промпты A -> B -> A, повторный A взят из кэша
#     (4 токена вместо 18691) ДАЖЕ на -c 32768, куда два промпта физически не помещаются.
#     Слот при `--parallel 1` один и капится по n_ctx_train, так что ячейки сверх 262144 всё
#     равно некому использовать. Нужно больше горячих сессий — поднимать `-cram`, а не `-c`.
#  2. Раздутый пул упирается в ОБРЫВ. Замер (IQ2_XXS, MTP, графика выключена):
#       -c 32768/262144/393216/425984/458752/491520 -> 72…74 т/с, RSS ~2.8 ГиБ, GPU занят на 95%
#       -c 524288                                   -> 27 т/с,    RSS 4.4 ГиБ, GPU занят на 29%
#     При переходе на 524288 видеопамять выросла на 36 МиБ, а ОПЕРАТИВНАЯ на 1567 МиБ: остаток
#     KV не поместился на карту и лёг в системную память, и каждый токен пошёл через шину.
#     Чередование 491520/524288/491520/524288 воспроизвело это четыре раза подряд.
#     Признак утечки один и тот же для любой конфигурации: RSS процесса заметно выше ~2.4 ГиБ
#     при одновременном простое GPU — именно так ловится Q4_K_XL на полном окне (RSS 5.1 ГиБ).
KV_POOL="${KV_POOL:-262144}"

# ЧИСЛО СЛОТОВ. ОДИН — для агентной работы с длинным контекстом это оптимум, а не компромисс.
# Замер (4 сессии по 80781 токену, одна и та же работа, стенное время до последнего ответа):
#   1 слот  -> 149.3 с   (очередь; 323124 токена = 2164 т/с, близко к одиночному пределу карты)
#   2 слота -> 276.9 с
#   4 слота -> 355.9 с   (с -b 8192 -ub 2048: 305.9 с; с -b 16384 -ub 4096: 292.3 с)
#   8 слотов на перегруженном пуле -> генерация падает до 0.94 т/с на сессию
# То есть слоты для ДЛИННЫХ контекстов не складываются, а конкурируют: предобработка и так
# насыщает карту, а расщепление добавляет накладные расходы без выигрыша в параллелизме.
# Даже последний в очереди запрос при одном слоте заканчивается раньше (149 с против 356 с).
# ! Обратное верно для КОРОТКИХ запросов: там 2 слота дают +48%, а 4 на 5090 — до 341 т/с
#   суммарно. Прежняя рекомендация «слотов побольше» была получена промптами по 27 токенов,
#   то есть мерила только декодирование, и для агентной нагрузки оказалась вредной.
# Переключение между сессиями при одном слоте не страдает: кэш промптов живёт в ОЗУ
# (`--cache-ram`), простаивающий слот сохраняется туда и восстанавливается при возврате.
PARALLEL="${PARALLEL:-1}"

M=$(ls /mnt/4tb/.cache/huggingface/hub/models--unsloth--Qwen3.8-27B-GGUF/snapshots/*/Qwen3.8-27B-"$QUANT".gguf 2>/dev/null | head -1)
[ -n "$M" ] || { echo "квант $QUANT не найден в кэше HF"; exit 1; }
echo "модель: $M"
echo "пул: $KV_POOL | слотов: $PARALLEL | проверить после загрузки: RSS ~2.3 ГиБ и загрузка GPU ~95% на генерации"
# reasoning_effort=medium: дефолтный xhigh на тяжёлых задачах не сходится за бюджет.
exec /mnt/4tb/llm/unsloth-studio/llama.cpp/llama-server \
  -m "$M" \
  --host 0.0.0.0 --port 8080 \
  -c "$KV_POOL" \
  --cache-type-k q4_0 --cache-type-v q4_0 \
  --flash-attn on --jinja -ngl -1 --kv-unified --parallel "$PARALLEL" \
  --spec-type draft-mtp --spec-draft-n-max 2 \
  --min-p 0 --top-k 20 --top-p 0.95 --temp 1.0 \
  --chat-template-kwargs '{"reasoning_effort":"medium"}'
