// Считает медиану. Для чётной длины должен усреднять два центральных элемента.
pub fn median(xs: &mut Vec<i64>) -> f64 {
    xs.sort();
    let n = xs.len();
    if n % 2 == 1 {
        xs[n / 2] as f64
    } else {
        // BUG: оба индекса одинаковы - усредняется один и тот же элемент.
        (xs[n / 2] as f64 + xs[n / 2] as f64) / 2.0
    }
}
