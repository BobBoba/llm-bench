#!/usr/bin/env bash
# Кампания qwen38-ctrl0819 [[19.08.2026]] — КОНТРОЛЬНОЕ сравнение квантов на ОДИНАКОВОМ окне.
#
# Зачем, хотя лестница уже отработала: там каждый квант мерился на СВОЁМ максимуме окна, и
# результат оказался перевёрнутым — IQ2_XXS (8.4 ГиБ, 2 бита) 18/22 против Q4_K_XL (16.7 ГиБ)
# 12/22. У такого результата есть три объяснения, и лестница их не различает:
#   (а) младшие кванты действительно не хуже (гипотеза владельца);
#   (б) Q4 проигрывает не квантом, а УЗКИМ ОКНОМ (81920 против 262144) — две задачи edit-long
#       ему просто недоступны;
#   (в) разброс: один прогон на юнит при temperature 1.0.
# Гипотеза «старшие кванты выжигают бюджет размышлений» уже ОТВЕРГНУТА замером: провалов с
# finish=length 0–2 на квант, то есть ответы настоящие.
#
# Здесь окно — константа 65536 (единственное, которое держат ВСЕ пять квантов, включая Q4).
# На нём edit-long недоступен ОДИНАКОВО для всех, поэтому сравниваются ровно 18 коротких задач
# и различие можно приписать кванту. Заодно это ВТОРОЙ прогон тех же 18 задач для каждого
# кванта — расхождение с лестницей даёт оценку разброса.
set -u
cd "$(dirname "$0")/.."
export LLAMA_SERVER_BASE=http://gaming-pc.lan:8888/v1
export LLAMA_SERVER_KEY_FILE=/tmp/.unsloth-gp
REPO="unsloth/Qwen3.8-27B-GGUF"
CTX=65536
LOG=results/qwen38-ctrl0819.log
: > "$LOG"
VS="LLM_TEMPERATURE=1.0 LLM_TOP_P=0.95 LLM_TOP_K=20"

# Порядок НЕ алфавитный: сперва крайние точки контраста (младший против старшего), чтобы при
# нехватке ночи главный вопрос «деградирует ли качество с квантом» был закрыт первым.
for q in UD-IQ2_XXS UD-Q4_K_XL UD-Q2_K_XL UD-Q3_K_XL UD-IQ2_M; do
  tag=$(echo "$q" | tr 'A-Z' 'a-z' | tr -d '_')
  echo "=== КОНТРОЛЬ $q @ $CTX ===" >> "$LOG"
  # страховка от перезапуска Studio: без неё квант записывается сплошными network-ошибками
  bash tools/wait-studio.sh 900 >> "$LOG" 2>&1 || { echo "$q: Studio недоступна, пропуск" >> "$LOG"; continue; }
  bash tools/ladder-probe.sh "$REPO:$q" "$CTX" >> "$LOG" 2>&1
  env $VS MAX_TOKENS=40000 LLM_DEADLINE_MS=2400000 \
    OUT="results-EXP-qwen38ctrl-$tag.json" node runners/run-hard.mjs "$REPO:$q" >> "$LOG" 2>&1
  node -e "
    const rs=require('./results/results-EXP-qwen38ctrl-$tag.json');
    const short=rs.filter(r=>r.task!=='edit-long');
    console.log('$q @ $CTX: коротких решено '+short.filter(r=>r.solved).length+'/'+short.length);
  " >> "$LOG" 2>&1
done

echo "=== qwen38-ctrl0819: завершено ===" >> "$LOG"
# GUI намеренно остаётся выключенным (указание владельца на эту ночь).
