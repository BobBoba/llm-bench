#!/usr/bin/env bash
# Кампания qwen38-cliff0819 [[19.08.2026]] — БИСЕКЦИЯ ОБРЫВА ПОИСКА по длине контекста.
# Повод: в лестнице квантов Q2_K_XL дал 8/8 на 131k и 0/8 на ~194k (движок обработал промпт
# ЦЕЛИКОМ — `n_tokens = 193992, truncated = 0`, то есть это отказ модели, а не стека).
# Вопрос владельца «лучшая пара квант↔контекст» без этой границы не решается: окно, которое
# ЗАГРУЖАЕТСЯ, и окно, на котором модель ЕЩЁ НАХОДИТ информацию, — разные числа, и второе
# и есть практический потолок.
#
# Меряем recall на промежуточных глубинах для каждого кванта, у которого максимум > 131k.
# Ступени идут ОТ БОЛЬШЕЙ к меньшей, чтобы раньше увидеть границу; каждая ступень ~3-5 мин.
set -u
cd "$(dirname "$0")/.."
export LLAMA_SERVER_BASE=http://gaming-pc.lan:8888/v1
export LLAMA_SERVER_KEY_FILE=/tmp/.unsloth-gp
REPO="unsloth/Qwen3.8-27B-GGUF"
LOG=results/qwen38-cliff0819.log
: > "$LOG"
VS="LLM_TEMPERATURE=1.0 LLM_TOP_P=0.95 LLM_TOP_K=20"

cliff() {  # $1 = квант, $2 = окно загрузки, $3 = список ступеней через запятую
  local q="$1" ctx="$2" rungs="$3" tag
  tag=$(echo "$q" | tr 'A-Z' 'a-z' | tr -d '_')
  echo "=== $q @ $ctx: обрыв на ступенях $rungs ===" >> "$LOG"
  bash tools/wait-studio.sh 900 >> "$LOG" 2>&1 || { echo "$q: Studio недоступна, пропуск" >> "$LOG"; return; }
  bash tools/ladder-probe.sh "$REPO:$q" "$ctx" >> "$LOG" 2>&1
  env $VS LLM_DEADLINE_MS=2400000 CTX="$ctx" RUNGS="$rungs" \
    OUT="results-EXP-qwen38q-$tag-cliff.json" node runners/run-multineedle.mjs "$REPO:$q" >> "$LOG" 2>&1
}

# Q2: 8/8 на 131k, 0/8 на ~194k -> ищем границу. 196608 ПОВТОРЯЕМ первым: IQ2_M (квант МЛАДШЕ!)
# на той же глубине дал 8/8, поэтому ноль Q2 может оказаться выбросом сэмплинга при t=1.0,
# а не свойством кванта. Один прогон на точку — слабое доказательство, повтор обязателен.
cliff UD-Q2_K_XL  262144 "147456,163840,180224,196608"
# Q3: 8/8 на 172k -> проверяем, держится ли выше (его максимум загрузки 229376)
cliff UD-Q3_K_XL  229376 "194560,212992"
# IQ2_M: младший квант на полном окне — где его граница
cliff UD-IQ2_M    262144 "163840,196608,229376"

echo "=== qwen38-cliff0819: завершено ===" >> "$LOG"
# GUI намеренно остаётся выключенным (указание владельца на эту ночь).
